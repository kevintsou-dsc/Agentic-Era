def main(dry):
    for (aid, slug), edits in EDITS.items():
        f = ROOT / "src" / "data" / "stories" / f"{aid}.ts"
        t = f.read_text(encoding="utf-8")
        notes_f = ROOT / "content" / "review" / "notes" / f"{slug}.json"
        notes = json.loads(notes_f.read_text(encoding="utf-8")) if notes_f.exists() else []
        paths = {u["id"]: u["path"] for u in json.loads((ROOT / "content" / "review" / "compression" / f"{slug}.before.units.json").read_text(encoding="utf-8"))["units"]}
        for mid, sym, old, new, why in edits:
            n = t.count(old)
            if n != 1:
                print(f"  ✗ {slug} {mid}：原句出現 {n} 次")
                continue
            t = t.replace(old, new)
            grow = len(new) / len(old) - 1
            notes = [x for x in notes if x.get("id") != f"compression-{mid}"]
            notes.append({"id": f"compression-{mid}", "path": paths[mid], "before": old, "after": new,
                          "reason": f"過度濃縮（{sym}）：{why}", "growth": round(grow, 2)})
            print(f"  {slug} {mid} {sym}：+{grow:.0%}")
        if not dry:
            f.write_text(t, encoding="utf-8")
            notes_f.parent.mkdir(parents=True, exist_ok=True)
            notes_f.write_text(json.dumps(notes, ensure_ascii=False, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main("--dry" in sys.argv)
